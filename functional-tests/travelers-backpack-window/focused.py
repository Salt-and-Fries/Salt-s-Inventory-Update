"""Run only backpack-window checks; not the complete gameplay suite."""
import json
import probe as p

(p.OUT/'focused-checks.json').write_text('[]')
s=p.start();w=p.window(s)
p.check('Default tier uses the Traveler native template and 27 storage cells',w['template'].endswith('TravelersWindows$Template') and w['nativeValues']['BACKPACK_INV_END']==27)
p.check('Four native inventory-management buttons excluded from layout',not any(r['id'].startswith('sort') for r in w['composition']['regions']) and any(r['id']=='edit-tools' for r in w['composition']['regions']))
p.check('Server locks the open physical backpack',p.server()['selectedLocked'])
p.save('base-window')
p.widget('ToolSlotsWidget',5,5)
p.check('Edit Tools opens the original tool drawer',p.window()['nativeValues']['showTools'])
p.seed(0,'minecraft:iron_pickaxe');p.slot(0);p.slot(27)
m=p.backpack_menu()
p.check('Tool drawer accepts a tool and keeps its exact stack','iron_pickaxe' in m['slots'][27]['item'] and 'Count:0b' in m['slots'][0]['item'])
p.seed(1,'minecraft:stone',6);p.slot(1);p.slot(28)
m=p.backpack_menu()
p.check('Tool drawer rejects ordinary blocks','minecraft:stone' in m['carried'] and 'Count:0b' in m['slots'][28]['item'])
p.slot(1);p.save('tools-open')
p.widget('ToolSlotsWidget',5,5)
p.check('Edit Tools closes the drawer',not p.window()['nativeValues']['showTools'])
p.act('close');p.check('Closing releases the physical backpack lock',not p.server()['selectedLocked'])

s=p.start(True);w=p.window(s)
p.check('Netherite tier retains 99 storage / six tool / six upgrade cells',w['nativeValues']['BACKPACK_INV_END']==99 and w['nativeValues']['TOOL_END']-w['nativeValues']['TOOL_START']==6 and w['nativeValues']['UPGRADE_END']-w['nativeValues']['UPGRADE_START']==6)
p.save('upgraded-window')
p.widget('CraftingWidget')
p.seed(0,'minecraft:oak_log',2);p.slot(0);p.slot(147)
w=p.window();m=p.backpack_menu()
p.check('Crafting result reaches the SIU window',w['slots'][156]['item']=='minecraft:oak_planks' and w['slots'][156]['count']==4)
p.slot(156);p.slot(2);m=p.backpack_menu()
p.check('Crafting consumes one log and yields four planks','Count:1b' in m['slots'][147]['item'] and 'Count:4b' in m['slots'][2]['item'] and 'oak_planks' in m['slots'][2]['item'])
p.save('crafting-open')
p.widget('CraftingWidget')
p.widget('TankWidget');p.save('tanks-open')
p.check('Tank upgrade expands its original controls',next(a for a in p.window()['nativeValues']['customWidgets'] if a['type']=='TankWidget')['open'])
p.widget('TankWidget')
p.widget('AbstractSmeltingWidget');p.save('furnace-open')
p.check('Furnace upgrade expands its native input, fuel and output',next(a for a in p.window()['nativeValues']['customWidgets'] if a['type']=='AbstractSmeltingWidget')['open'])
p.widget('AbstractSmeltingWidget')
p.widget('AutoPickupWidget');p.save('pickup-open')
p.check('Pickup upgrade expands its native filter panel',next(a for a in p.window()['nativeValues']['customWidgets'] if a['type']=='AutoPickupWidget')['open'])
p.widget('AutoPickupWidget')
p.widget('MagnetWidget');p.save('magnet-open')
p.check('Magnet upgrade expands its native filter panel',next(a for a in p.window()['nativeValues']['customWidgets'] if a['type']=='MagnetWidget')['open'])
p.widget('MagnetWidget')
p.widget('VoidWidget');p.save('void-open')
p.check('Void upgrade expands its native filter panel',next(a for a in p.window()['nativeValues']['customWidgets'] if a['type']=='VoidWidget')['open'])
p.widget('VoidWidget')
p.widget('SettingsWidget');w=p.window()
p.check('Settings opens as the original settings menu',w['menuId']=='travelersbackpack:backpack_settings')
p.widget('UnsortablesWidget');p.slot(0)
s=p.save('settings-unsortable')
p.check('Unsortable selection is saved immediately','UnsortableSlots:[0]' in s['held'])
p.widget('MemoryWidget');p.slot(12);s=p.save('settings-memory')
p.check('Memory slot selection is persisted','MemorySlots' in s['held'] and 'bread' in s['held'])
p.widget('SettingsWidget');w=p.window()
p.check('Return from settings restores backpack storage',w['menuId']=='travelersbackpack:backpack_item')
p.act('inventory');p.save('workspace')
p.check('Player inventory stays available as a separate SIU window',any(w['kind']=='INVENTORY' for w in p.act()['workspaceWindows']))
print('Focused backpack checks complete.',flush=True)
